"""Charts and RESULTS.md for the v2 model, generated from reports/v2/results.json.

    python -m churn2.report
"""
import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from sklearn.metrics import roc_curve  # noqa: E402

from churn import config  # noqa: E402

R = config.REPORTS_DIR / "v2"
INK, ACC, GREY, RED = "#1a1a1a", "#00594C", "#8A8F8B", "#B4372B"

LABELS = {
    "rec.days_silent_beyond_week": "Days silent beyond a normal week",
    "mem.share_lic_dtc": "Share of members licensed for DNS Traffic Control",
    "firmo.log_employees": "Customer employee count (log)",
    "total_queries": "Daily DNS queries (24 h counter)",
    "mem.upgrade_events_365d": "NIOS upgrades per member, last 12 months",
    "mem.share_lic_rpz": "Share of members licensed for RPZ (DNS firewall)",
    "grid_feature_usage.dtc.members_pct": "% of members licensed for DTC (grid view)",
    "mem.member_object_count_sum": "Database objects across members",
    "mem.member_disk_size_mean": "Average member disk size (GB)",
    "grid_dashboard_count": "Dashboards configured",
}


def lab(f):
    return LABELS.get(f, f)


def fmt(v):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "–"
    a = abs(v)
    if a >= 1e6:
        return f"{v / 1e6:.1f}M"
    if a >= 1e4:
        return f"{v / 1e3:.0f}K"
    if a >= 100:
        return f"{v:,.0f}"
    return f"{v:.3g}"


def charts(out):
    p = out["primary"]
    # 1 forward selection path
    fs = pd.read_csv(R / "forward_selection.csv")
    fig, ax = plt.subplots(figsize=(8, 3.8))
    ax.plot(fs.step, fs.cv_auc, "o-", color=ACC, lw=2)
    ax.fill_between(fs.step, fs.cv_auc - fs.cv_auc_sd, fs.cv_auc + fs.cv_auc_sd, color=ACC, alpha=0.12)
    for _, r in fs.iterrows():
        ax.annotate(("" if r.accepted else "REJECTED: ") + lab(r.feature) + f"\np={r.p:.1g}",
                    (r.step, r.cv_auc), textcoords="offset points", xytext=(6, -18), fontsize=7,
                    color=INK if r.accepted else RED)
    ax.set(xlabel="Parameters in model", ylabel="Cross-validated AUC (dev)", title="Forward selection: each step must be significant")
    ax.set_xlim(0.5, len(fs) + 1.8)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(); fig.savefig(R / "forward_selection.png", dpi=150); plt.close(fig)
    # 2 test ROC
    tp = pd.read_pickle(config.DATA_DIR / "v2_test_predictions.pkl")
    fpr, tpr, _ = roc_curve(tp.label, tp.p)
    fig, ax = plt.subplots(figsize=(4.6, 4.4))
    ax.plot(fpr, tpr, color=ACC, lw=2.5, label=f"Final model, AUC {p['test']['roc_auc']:.2f}")
    ax.plot([0, 1], [0, 1], color="#ccc", lw=1)
    ax.set(xlabel="False-positive rate", ylabel="True-positive rate (recall)", title="Locked test set")
    ax.legend(frameon=False, fontsize=8, loc="lower right")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(); fig.savefig(R / "test_roc.png", dpi=150); plt.close(fig)
    if "stability" in out:
        st = out["stability"]
        fig, ax = plt.subplots(1, 2, figsize=(11, 4))
        ax[0].hist(st["test_auc"], bins=12, color=ACC, alpha=0.85)
        ax[0].axvline(np.mean(st["test_auc"]), color=INK, lw=1.5, ls="--")
        ax[0].set(xlabel="Test AUC", ylabel="Random splits", title=f"Whole pipeline repeated on {st['n_splits']} random splits")
        sf = pd.Series(st["selection_frequency"]).sort_values().tail(12)
        ax[1].barh([lab(i) for i in sf.index], sf.values, color=[ACC if v >= 0.5 else GREY for v in sf.values])
        ax[1].set(xlabel="Share of splits where selected", title="Which parameters keep getting chosen")
        ax[1].set_xlim(0, 1)
        for a in ax:
            a.spines[["top", "right"]].set_visible(False)
        fig.tight_layout(); fig.savefig(R / "stability.png", dpi=150); plt.close(fig)


def markdown(out):
    p, t, d = out["primary"], out["primary"]["test"], out["dataset"]
    S = pd.read_csv(R / "screening.csv")
    C = pd.DataFrame(out["coefficients"])
    L = ["# Churn model v2: results", "", "Generated by `python -m churn2.report`. Do not edit by hand.", "",
         "## Data", "",
         f"- **{d['churned_grids']} churned grids** ({d['churned_accounts']} accounts) vs **{d['grids'] - d['churned_grids']} retained grids** "
         f"({d['retained_accounts']} accounts); {d['candidate_parameters']} candidate parameters per grid.",
         f"- Locked test set: {p['n_test']} grids. Development set: {p['n_dev']} grids.", "",
         "## Selection funnel (development set only)", "",
         "| Stage | Parameters |", "|---|---:|",
         f"| Candidates | {d['candidate_parameters']} |",
         f"| Enough coverage and variation to test | {p['screened']} |",
         f"| Significant (FDR q < 0.01), meaningful effect, and stable over time | {p['passed_screen']} |",
         f"| After removing correlated duplicates (\\|ρ\\| ≥ 0.7) | {p['after_decorrelation']} |",
         f"| **Each adding significant accuracy (forward selection)** | **{len(p['selected'])}** |", "",
         "## The final model", "",
         f"Logistic regression. Parameters are transformed x → sign(x)·log(1+\\|x\\|) and standardised. "
         f"Intercept {out['intercept']:.3f}, McFadden pseudo-R² {out['mcfadden_pseudo_r2']:.3f}.", "",
         "| Parameter | Odds ratio per SD (95% CI) | p-value | VIF | Median churned | Median retained |",
         "|---|---:|---:|---:|---:|---:|"]
    Sx = S.set_index("feature")
    for r in C.itertuples():
        L.append(f"| {lab(r.feature)} | {r.odds_ratio_per_sd:.2f} ({r.or_ci_low:.2f}–{r.or_ci_high:.2f}) | {r.p_value:.1g} | "
                 f"{r.vif:.2f} | {fmt(Sx.median_churned[r.feature])} | {fmt(Sx.median_retained[r.feature])} |")
    L += ["", "## Model comparison (development set, 5×5 repeated cross-validation)", "",
          "| Model | Parameters | CV AUC | p (better than logistic?) |", "|---|---:|---:|---:|"]
    for n, m in p["model_comparison"].items():
        L.append(f"| {n} | {m['n_features']} | {m['dev_cv_auc']:.3f} ± {m['dev_cv_auc_sd']:.3f} | "
                 f"{m.get('p_better_than_logistic', float('nan')):.2f} |")
    L += ["", f"**Chosen: {p['winner']}** (the parsimony rule keeps logistic unless another model is significantly better at p < 0.01).", "",
          "## Locked test set (evaluated once)", "",
          "| Measure | Value |", "|---|---:|",
          f"| ROC-AUC (95% bootstrap CI, clustered by account) | **{t['roc_auc']:.3f}** ({t['roc_auc_ci95'][0]:.3f}–{t['roc_auc_ci95'][1]:.3f}) |",
          f"| Label-permutation p-value | {t['perm_p_value']:.3g} |",
          f"| PR-AUC (base rate {t['churned'] / t['n']:.1%}) | {t['pr_auc']:.3f} |",
          f"| Threshold (fixed on dev) | {t['threshold']:.3f} |",
          f"| Recall (churners caught) | {t['recall']:.1%} ({t['tp']} of {t['tp'] + t['fn']}) |",
          f"| Precision (flags that churned) | {t['precision']:.1%} |",
          f"| Specificity | {t['specificity']:.1%} |",
          f"| Accuracy / balanced accuracy | {t['accuracy']:.1%} / {t['balanced_accuracy']:.1%} |",
          f"| F1 | {t['f1']:.3f} |",
          f"| Brier score | {t['brier']:.3f} |",
          f"| Precision if real-world churn rate were 5% / 10% / 20% | {t['precision_if_churn_rate_5pct']:.1%} / "
          f"{t['precision_if_churn_rate_10pct']:.1%} / {t['precision_if_churn_rate_20pct']:.1%} |",
          f"| Account level (flag if any grid flagged): AUC / recall / precision | {t['account_level']['roc_auc']:.3f} / "
          f"{t['account_level']['recall']:.1%} / {t['account_level']['precision']:.1%} |", ""]
    if "stability" in out:
        st = out["stability"]
        a = np.array(st["test_auc"])
        L += [f"## Stability: whole pipeline repeated on {st['n_splits']} random splits", "",
              f"- Test AUC mean **{a.mean():.3f}**, 2.5–97.5 percentile {np.percentile(a, 2.5):.3f}–{np.percentile(a, 97.5):.3f}, "
              f"min {a.min():.3f}, max {a.max():.3f}.",
              f"- Recall mean {np.nanmean(st['test_recall']):.1%}, precision mean {np.nanmean(st['test_precision']):.1%}.",
              f"- Parameters selected per split: median {int(np.median(st['n_selected']))} (range {min(st['n_selected'])}–{max(st['n_selected'])}).",
              f"- Winning model per split: {st['winners']}.",
              f"- Mean test AUC by model: " + ", ".join(f"{k} {v:.3f}" for k, v in st["test_auc_all_models_mean"].items()) + ".", "",
              "| Parameter | Selected in % of splits |", "|---|---:|"]
        for f, v in list(st["selection_frequency"].items())[:12]:
            L.append(f"| {lab(f)} | {v:.0%} |")
        L.append("")
    if "robustness" in out:
        L += ["## Robustness", "", "| Variant | Grids (churned) | Test AUC | Selected |", "|---|---:|---:|---|"]
        for n, v in out["robustness"].items():
            if n == "negative_control_shuffled_labels":
                continue
            L.append(f"| {n} | {v['n']} ({v['churned']}) | {v['test_auc']:.3f} | {', '.join(lab(x) for x in v['selected'])} |")
        nc = out["robustness"]["negative_control_shuffled_labels"]
        L += ["", f"**Negative control:** with labels randomly shuffled, the full pipeline gives test AUC "
              f"{', '.join(f'{x['test_auc']:.3f}' for x in nc)} and selects "
              f"{', '.join(str(len(x['selected'])) for x in nc)} parameters. That's chance level, so the pipeline doesn't manufacture signal.", ""]
    excl = S[S.era_drift & (S.q < 0.01) & (S.effect >= 0.05)]
    L += ["## Parameters excluded because they drift with calendar date", "",
          "| Parameter | AUC | ρ with date (churners) |", "|---|---:|---:|"]
    for r in excl.itertuples():
        L.append(f"| `{r.feature}` | {r.auc:.3f} | {r.era_rho:+.2f} |")
    L += ["", "## All parameters that passed screening (strongest first)", "",
          "| Parameter | AUC alone | Direction | Median churned | Median retained | q-value |", "|---|---:|---|---:|---:|---:|"]
    for r in S[S.passed].itertuples():
        L.append(f"| `{r.feature}` | {r.auc:.3f} | {'higher → churn' if r.auc > 0.5 else 'lower → churn'} | "
                 f"{fmt(r.median_churned)} | {fmt(r.median_retained)} | {r.q:.1g} |")
    (R / "RESULTS.md").write_text("\n".join(L) + "\n")


def main():
    out = json.loads((R / "results.json").read_text())
    charts(out)
    markdown(out)
    print(f"wrote {R}/RESULTS.md and charts")


if __name__ == "__main__":
    main()
